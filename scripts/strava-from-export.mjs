#!/usr/bin/env node
/**
 * Rewrites src/content/hobbies/outdoors-stats.json from a Strava data export.
 *
 * Usage:
 *   node scripts/strava-from-export.mjs path/to/activities.csv [--year 2026] [--types Hike,Run,Walk]
 *     [--tz America/Los_Angeles] [--dry-run]
 *
 * Get the CSV from strava.com -> Settings -> My Account -> Download or Delete Your Account -> Request your archive.
 * Only activities.csv from the zip is needed. Do not commit the CSV or the rest of the export: only the
 * summed miles below end up in the repo.
 */
import fs from "node:fs";
import path from "node:path";

const OUT = path.join(import.meta.dirname, "..", "src/content/hobbies/outdoors-stats.json");
const METERS_PER_MILE = 1609.344;

const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(name);
  return i === -1 ? undefined : args[i + 1];
};
const csvPath = args.find((a, i) => !a.startsWith("--") && !args[i - 1]?.startsWith("--"));
const dryRun = args.includes("--dry-run");
const year = Number(flag("--year") ?? new Date().getFullYear());
const types = (flag("--types") ?? "Hike,Run").split(",").map((t) => t.trim().toLowerCase());
const tz = flag("--tz") ?? "America/Los_Angeles";

if (!csvPath) {
  console.error("Usage: node scripts/strava-from-export.mjs path/to/activities.csv [--year YYYY] [--types Hike,Run,Walk] [--dry-run]");
  process.exit(1);
}

/** RFC 4180 CSV: quoted fields may contain commas, quotes ("") and newlines. */
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((f) => f !== ""));
}

const [header, ...records] = parseCsv(fs.readFileSync(csvPath, "utf8").replace(/^﻿/, ""));

// The export repeats some column names. "Distance" appears twice: the first in the
// athlete's display unit (km or miles, as formatted text), the second in meters.
const indexes = (name) => header.flatMap((h, i) => (h === name ? [i] : []));
const col = {
  date: indexes("Activity Date")[0],
  type: indexes("Activity Type")[0],
  meters: indexes("Distance")[1],
};
for (const [k, v] of Object.entries(col)) {
  if (v === undefined) {
    console.error(`activities.csv is missing the expected column for "${k}". Strava may have changed the export format.`);
    process.exit(1);
  }
}

// "Activity Date" is UTC, e.g. "Jun 3, 2024, 3:12:45 PM". Bucket by the local calendar
// (--tz) so an evening hike on the last day of a month counts toward that month.
const localParts = new Intl.DateTimeFormat("en-US", { timeZone: tz, year: "numeric", month: "numeric" });
const parseDate = (s) => {
  const d = new Date(`${s} UTC`);
  if (Number.isNaN(d.getTime())) return null;
  const p = Object.fromEntries(localParts.formatToParts(d).map((x) => [x.type, x.value]));
  return { year: Number(p.year), month: Number(p.month) - 1 };
};

const byType = new Map();
const monthly = Array(12).fill(0);
let allTime = 0, thisYear = 0, counted = 0, skipped = 0, since = null;

for (const r of records) {
  const type = r[col.type] ?? "";
  const meters = Number(r[col.meters]);
  const date = parseDate(r[col.date] ?? "");
  const t = byType.get(type) ?? { n: 0, miles: 0 };
  t.n++;
  if (Number.isFinite(meters)) t.miles += meters / METERS_PER_MILE;
  byType.set(type, t);

  if (!types.includes(type.toLowerCase())) continue;
  if (!Number.isFinite(meters) || !date) { skipped++; continue; }
  const miles = meters / METERS_PER_MILE;
  counted++;
  allTime += miles;
  if (since === null || date.year < since) since = date.year;
  if (date.year === year) {
    thisYear += miles;
    monthly[date.month] += miles;
  }
}

console.log("Activity types in the export:");
for (const [type, t] of [...byType].sort((a, b) => b[1].miles - a[1].miles)) {
  const mark = types.includes(type.toLowerCase()) ? "*" : " ";
  console.log(` ${mark} ${type.padEnd(18)} ${String(t.n).padStart(4)} activities  ${t.miles.toFixed(1).padStart(8)} mi`);
}
console.log(`Counting ${types.join(", ")} (*): ${counted} activities${skipped ? `, ${skipped} skipped (no distance or date)` : ""}.`);

const next = {
  _readme:
    "Miles from Strava (activity types in `types`). GENERATED by scripts/strava-from-export.mjs from a Strava data export (activities.csv); rerun it with a fresh export to update. `since` is the year of the first counted activity. Keep these field names so the page does not need to change.",
  sample: false,
  updated: new Date().toISOString().slice(0, 10),
  types: types.map((t) => t[0].toUpperCase() + t.slice(1)),
  year,
  since,
  milesThisYear: Math.round(thisYear),
  milesAllTime: Math.round(allTime),
  milesByMonth: monthly.map((m) => Math.round(m)),
};
console.log(JSON.stringify({ ...next, _readme: undefined }, null, 2));

if (dryRun) console.log("(dry run, nothing written)");
else {
  fs.writeFileSync(OUT, JSON.stringify(next, null, 2) + "\n");
  console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
}
